returns trigger
language plpgsql
set search_path = public
as $$
begin
  if (to_jsonb(old) ->> tg_argv[0]) is distinct from (to_jsonb(new) ->> tg_argv[0]) then
    raise exception '% is immutable', tg_argv[0] using errcode = '22000';
  end if;
  return new;
end;
$$;

