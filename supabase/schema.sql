create or replace function public.checkout_order(
  p_location_id uuid,
  p_temple_id text,
  p_qr_nonce uuid,
  p_cashier_id uuid,
  p_lines jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_location public.locations%rowtype;
  v_cashier public.profiles%rowtype;
  v_line record;
  v_order_id uuid;
  v_week_start date;
  v_points_spent bigint;
  v_total_points bigint := 0;
  v_previous_quantity bigint;
  v_requested_count integer;
  v_locked_count integer;
  v_catalog_locked_count integer;
begin
  if p_temple_id is null or p_temple_id <> btrim(p_temple_id)
      or length(p_temple_id) not between 1 and 128 then
    raise exception 'A normalized Temple ID is required' using errcode = '22023';
  end if;
  if p_qr_nonce is null then
    raise exception 'A QR nonce is required' using errcode = '22023';
  end if;
  if p_lines is null or jsonb_typeof(p_lines) is distinct from 'array' then
    raise exception 'At least one item is required' using errcode = '22023';
  end if;
  if jsonb_array_length(p_lines) = 0 then
    raise exception 'At least one item is required' using errcode = '22023';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_lines) as line(value)
    where jsonb_typeof(line.value) <> 'object'
       or coalesce(line.value ->> 'item_id', '') !~ '^[1-9][0-9]{0,9}$'
       or coalesce(line.value ->> 'quantity', '') !~ '^[1-9][0-9]?$'
  ) then
    raise exception 'Each item must have a positive item_id and quantity from 1 to 99'
      using errcode = '22023';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_lines) as line(value)
    where (line.value ->> 'item_id')::bigint > 2147483647
  ) then
    raise exception 'An item_id is out of range' using errcode = '22023';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_lines) as line(value)
    group by (line.value ->> 'item_id')::bigint
    having sum((line.value ->> 'quantity')::integer) > 99
  ) then
    raise exception 'Combined quantity for an item cannot exceed 99' using errcode = '22023';
  end if;

  select * into v_location
  from public.locations
  where id = p_location_id and active
  for share;
  if not found then
    raise exception 'Location is missing or inactive' using errcode = '22023';
  end if;

  select * into v_cashier
  from public.profiles
  where id = p_cashier_id
  for share;
  if not found or not (
    v_cashier.role = 'admin'
    or (v_cashier.role = 'cashier' and v_cashier.location_id = p_location_id)
  ) then
    raise exception 'Cashier is not authorized for this location' using errcode = '42501';
  end if;

  if exists (select 1 from public.orders where qr_nonce = p_qr_nonce) then
    raise exception 'QR code has already been redeemed' using errcode = '23505';
  end if;

  v_week_start :=
    (timezone(v_location.timezone, now())::date
      - ((extract(dow from timezone(v_location.timezone, now()))::integer
          - v_location.week_start_day + 7) % 7));

  perform pg_advisory_xact_lock(
    hashtextextended(p_location_id::text || ':' || p_temple_id, 0)
  );

  select count(*) into v_requested_count
  from (
    select (line.value ->> 'item_id')::integer as item_id
    from jsonb_array_elements(p_lines) as line(value)
    group by (line.value ->> 'item_id')::integer
  ) requested;

  perform li.item_id
  from public.location_items as li
  join (
    select (line.value ->> 'item_id')::integer as item_id
    from jsonb_array_elements(p_lines) as line(value)
    group by (line.value ->> 'item_id')::integer
  ) as requested using (item_id)
  where li.location_id = p_location_id
  order by li.item_id
  for update of li;
  get diagnostics v_locked_count = row_count;
  if v_locked_count <> v_requested_count then
    raise exception 'An item is not stocked at this location' using errcode = '22023';
  end if;

  perform i.id
  from public.items as i
  join (
    select (line.value ->> 'item_id')::integer as item_id
    from jsonb_array_elements(p_lines) as line(value)
    group by (line.value ->> 'item_id')::integer
  ) as requested using (item_id)
  order by i.id
  for share of i;
  get diagnostics v_catalog_locked_count = row_count;
  if v_catalog_locked_count <> v_requested_count then
    raise exception 'An item no longer exists' using errcode = '22023';
  end if;

  for v_line in
    select
      li.item_id,
      sum((request.value ->> 'quantity')::integer)::integer as quantity,
      li.amount,
      li.available,
      li.limit_per_person,
      coalesce(li.points_cost_override, i.points_cost) as points_each
    from jsonb_array_elements(p_lines) as request(value)
    join public.location_items as li
      on li.location_id = p_location_id
     and li.item_id = (request.value ->> 'item_id')::integer
    join public.items as i on i.id = li.item_id
    group by li.item_id, li.amount, li.available, li.limit_per_person,
             li.points_cost_override, i.points_cost
    order by li.item_id
  loop
    if not v_line.available or v_line.amount < v_line.quantity then
      raise exception 'Insufficient stock or item unavailable: %', v_line.item_id
        using errcode = '22023';
    end if;
    if v_line.points_each is null then
      raise exception 'Points cost is not configured for item %', v_line.item_id
        using errcode = '22023';
    end if;
    if v_line.limit_per_person is not null then
      select coalesce(sum(oi.quantity), 0) into v_previous_quantity
      from public.orders as o
      join public.order_items as oi on oi.order_id = o.id
      where o.location_id = p_location_id
        and o.temple_id = p_temple_id
        and o.created_at >= (v_week_start::timestamp at time zone v_location.timezone)
        and o.created_at < ((v_week_start + 7)::timestamp at time zone v_location.timezone)
        and oi.item_id = v_line.item_id;
      if v_previous_quantity + v_line.quantity > v_line.limit_per_person then
        raise exception 'Weekly item limit exceeded for item %', v_line.item_id
          using errcode = '22023';
      end if;
    end if;
    v_total_points := v_total_points + (v_line.quantity::bigint * v_line.points_each);
  end loop;

  select coalesce(sum(total_points), 0) into v_points_spent
  from public.orders
  where location_id = p_location_id
    and temple_id = p_temple_id
    and created_at >= (v_week_start::timestamp at time zone v_location.timezone)
    and created_at < ((v_week_start + 7)::timestamp at time zone v_location.timezone);
  if v_points_spent + v_total_points > v_location.weekly_points then
    raise exception 'Weekly points limit exceeded' using errcode = '22023';
  end if;

  insert into public.orders (location_id, temple_id, qr_nonce, cashier_id, total_points)
  values (p_location_id, p_temple_id, p_qr_nonce, p_cashier_id, v_total_points::integer)
  returning id into v_order_id;

  for v_line in
    select
      li.item_id,
      sum((request.value ->> 'quantity')::integer)::integer as quantity,
      coalesce(li.points_cost_override, i.points_cost) as points_each
    from jsonb_array_elements(p_lines) as request(value)
    join public.location_items as li
      on li.location_id = p_location_id
     and li.item_id = (request.value ->> 'item_id')::integer
    join public.items as i on i.id = li.item_id
    group by li.item_id, li.points_cost_override, i.points_cost
    order by li.item_id
  loop
    update public.location_items
    set amount = amount - v_line.quantity, updated_at = now()
    where location_id = p_location_id and item_id = v_line.item_id;
    insert into public.order_items (order_id, item_id, quantity, points_each, line_points)
    values (
      v_order_id, v_line.item_id, v_line.quantity, v_line.points_each,
      v_line.quantity * v_line.points_each
    );
  end loop;

  return v_order_id;
end;
$$;

